const state = {
    category: "Technology",
    level: "Easy",
    questions: [],
    index: 0,
    answers: [],
    seconds: 15,
    interval: null,
    player: "Player One",
    reviewOpen: false
};

const $ = id => document.getElementById(id);

function shuffle(array) {
    return [...array].sort(() => Math.random() - 0.5);
}

function escapeHTML(text) {
    return String(text).replace(/[&<>"']/g, char => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
    })[char]);
}

function init() {

    document.querySelectorAll(".category-card").forEach(card => {
        card.addEventListener("click", () => {
            chooseCategory(card.dataset.category);
        });
    });

    document.querySelectorAll(".difficulty").forEach(button => {
        button.addEventListener("click", () => {

            document.querySelectorAll(".difficulty")
                .forEach(item => item.classList.remove("active"));

            button.classList.add("active");
            state.level = button.dataset.level;
        });
    });

    $("exploreBtn").addEventListener("click", () => {
        $("categories").scrollIntoView({ behavior: "smooth" });
    });

    $("startBtn").addEventListener("click", startQuiz);

    $("nextBtn").addEventListener("click", nextQuestion);

    $("closeQuiz").addEventListener("click", () => {
        clearInterval(state.interval);
        $("quizModal").classList.add("hidden");
    });

    $("playAgainBtn").addEventListener("click", () => {
        $("resultModal").classList.add("hidden");
        startQuiz();
    });

    $("categoryAgainBtn").addEventListener("click", () => {
        $("resultModal").classList.add("hidden");
        $("categories").scrollIntoView({ behavior: "smooth" });
    });

    $("reviewBtn").addEventListener("click", toggleReview);

    renderLeaderboard();
}

function chooseCategory(category) {

    state.category = category;

    document.querySelectorAll(".category-card").forEach(card => {
        card.classList.toggle(
            "selected",
            card.dataset.category === category
        );
    });

    $("arenaDescription").textContent =
        category + " selected. Choose your difficulty and start.";

    $("arena").scrollIntoView({
        behavior: "smooth",
        block: "center"
    });
}

function startQuiz() {

    state.player = $("playerName").value.trim() || "Player One";

    const source = bank[state.category];

    state.questions = shuffle(source).slice(0, 10);

    state.index = 0;
    state.answers = [];
    state.reviewOpen = false;

    $("reviewList").classList.add("hidden");
    $("reviewBtn").textContent = "Review Answers";

    $("resultModal").classList.add("hidden");
    $("quizModal").classList.remove("hidden");

    showQuestion();
}

function showQuestion() {

    clearInterval(state.interval);

    state.seconds = 15;

    const question = state.questions[state.index];

    $("quizCategory").textContent =
        state.category + " · " + state.level;

    $("questionCounter").textContent =
        "QUESTION " + (state.index + 1) + " / 10";

    $("questionText").textContent = question.q;

    $("timerCircle").textContent = state.seconds;
    $("timerBar").style.width = "100%";

    $("answerHint").textContent = "Choose one answer.";

    $("nextBtn").disabled = true;

    $("nextBtn").textContent =
        state.index === 9 ? "View Results →" : "Next Question →";

    $("answerList").innerHTML = question.o.map((option, i) => `
        <button class="answer-option" data-answer="${i}">
            <span class="option-letter">
                ${String.fromCharCode(65 + i)}
            </span>
            <span>${escapeHTML(option)}</span>
        </button>
    `).join("");

    $("answerList").querySelectorAll("button").forEach(button => {
        button.addEventListener("click", () => {
            selectAnswer(Number(button.dataset.answer));
        });
    });

    state.interval = setInterval(() => {

        state.seconds--;

        $("timerCircle").textContent = state.seconds;

        $("timerBar").style.width =
            (state.seconds / 15 * 100) + "%";

        if (state.seconds <= 0) {

            clearInterval(state.interval);

            if (state.answers[state.index] === undefined) {
                state.answers[state.index] = null;
            }

            revealAnswer(true);
        }

    }, 1000);
}

function selectAnswer(answer) {

    if (state.answers[state.index] !== undefined) {
        return;
    }

    clearInterval(state.interval);

    state.answers[state.index] = answer;

    revealAnswer(false);
}

function revealAnswer(timedOut) {

    const question = state.questions[state.index];
    const chosen = state.answers[state.index];

    $("answerList").querySelectorAll("button").forEach((button, i) => {

        button.disabled = true;

        if (i === question.a) {
            button.classList.add("correct");
        }

        if (chosen === i && i !== question.a) {
            button.classList.add("wrong");
        }

    });

    if (timedOut) {
        $("answerHint").textContent =
            "Time is up! Correct answer highlighted.";
    } else if (chosen === question.a) {
        $("answerHint").textContent =
            "Correct! " + question.e;
    } else {
        $("answerHint").textContent =
            "Not quite. " + question.e;
    }

    $("nextBtn").disabled = false;
}

function nextQuestion() {

    if (state.answers[state.index] === undefined) {
        return;
    }

    if (state.index < state.questions.length - 1) {
        state.index++;
        showQuestion();
    } else {
        finishQuiz();
    }
}

function finishQuiz() {

    clearInterval(state.interval);

    $("quizModal").classList.add("hidden");

    const correct = state.questions.reduce((total, question, i) => {
        return total + (state.answers[i] === question.a ? 1 : 0);
    }, 0);

    const attempted = state.answers.filter(answer =>
        answer !== null && answer !== undefined
    ).length;

    const wrong = attempted - correct;

    const accuracy = Math.round(correct / 10 * 100);

    $("scoreValue").textContent = correct;
    $("correctValue").textContent = correct;
    $("wrongValue").textContent = wrong;
    $("accuracyValue").textContent = accuracy + "%";

    $("resultTitle").textContent =
        accuracy >= 80 ? "Brilliant Performance!" :
        accuracy >= 50 ? "Great Effort!" :
        "Keep Practising!";

    $("resultSubtitle").textContent =
        state.player + ", you completed " +
        state.category + " · " + state.level + ".";

    $("resultMessage").textContent =
        accuracy === 100 ? "Perfect score! You are a QuizVerse champion!" :
        accuracy >= 70 ? "Strong performance! Keep improving." :
        "Review your answers and try again.";

    saveScore({
        player: state.player,
        category: state.category,
        level: state.level,
        score: correct,
        total: 10,
        accuracy: accuracy,
        date: Date.now()
    });

    $("reviewList").innerHTML = state.questions.map((question, i) => {

        const chosen = state.answers[i];

        const yourAnswer =
            chosen === null || chosen === undefined
            ? "No answer"
            : question.o[chosen];

        return `
            <div class="review-item">
                <strong>${i + 1}. ${escapeHTML(question.q)}</strong>

                <div class="${chosen === question.a ? "right-answer" : "your-wrong"}">
                    Your answer: ${escapeHTML(yourAnswer)}
                </div>

                <div class="right-answer">
                    Correct answer: ${escapeHTML(question.o[question.a])}
                </div>

                <div>${escapeHTML(question.e)}</div>
            </div>
        `;

    }).join("");

    $("resultModal").classList.remove("hidden");

    renderLeaderboard();
}

function saveScore(entry) {

    try {

        const scores = JSON.parse(
            localStorage.getItem("quizverseScores") || "[]"
        );

        scores.push(entry);

        scores.sort((a, b) =>
            b.score - a.score ||
            b.accuracy - a.accuracy
        );

        localStorage.setItem(
            "quizverseScores",
            JSON.stringify(scores.slice(0, 10))
        );

    } catch (error) {
        console.log("Unable to save scores.");
    }
}

function renderLeaderboard() {

    let scores = [];

    try {
        scores = JSON.parse(
            localStorage.getItem("quizverseScores") || "[]"
        );
    } catch (error) {
        scores = [];
    }

    $("leaderboardRows").innerHTML = scores.slice(0, 5).map((score, i) => `
        <div class="leader-row">

            <span>
                ${i + 1}. ${escapeHTML(score.player)}
            </span>

            <span>${escapeHTML(score.category)}</span>

            <span class="score-text">
                ${score.score}/${score.total}
            </span>

            <span class="accuracy">
                ${score.accuracy}%
            </span>

        </div>
    `).join("");

    $("emptyLeaderboard").classList.toggle(
        "hidden",
        scores.length > 0
    );
}

function toggleReview() {

    state.reviewOpen = !state.reviewOpen;

    $("reviewList").classList.toggle(
        "hidden",
        !state.reviewOpen
    );

    $("reviewBtn").textContent =
        state.reviewOpen ? "Hide Answers" : "Review Answers";
}

